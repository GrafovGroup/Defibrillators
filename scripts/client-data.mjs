// Build a compact browser catalogue; labels and editorial metadata stay server-side.
import fs from 'node:fs';
import { format, resolveConfig } from 'prettier';
import { routes, pathFor } from '../src/data/routes.ts';
import { cityCatalogue, cityIds } from '../src/data/city-catalogue.ts';
import { provinceForLocation } from '../src/data/location-routes.ts';
import { modelIds } from '../src/data/model-options.ts';
import {
  partOptions,
  packageOptions,
  trainingOptions,
} from '../src/data/planning-options.ts';
const data = {
  pageIds: Object.keys(routes),
  cityIds,
  modelIds,
  sourcePaths: Object.fromEntries(
    Object.keys(routes).map((id) => [
      id,
      { en: pathFor(id, 'en'), fr: pathFor(id, 'fr') },
    ]),
  ),
  clientCities: Object.fromEntries(
    cityIds.map((id) => [
      id,
      { en: cityCatalogue[id].en, fr: cityCatalogue[id].fr },
    ]),
  ),
  clientProvinces: Object.fromEntries(
    Object.keys(routes)
      .map((id) => [id, provinceForLocation(id)])
      .filter(([, code]) => code),
  ),
  partIds: partOptions.map((p) => p.id),
  packageIds: packageOptions.map((p) => p.id),
  trainingChoices: Object.fromEntries(
    Object.entries(trainingOptions).map(([key, options]) => [
      key,
      options.map((p) => p.id),
    ]),
  ),
};
const declarations = Object.entries(data)
  .map(
    ([key, value]) =>
      `export const ${key} = ${JSON.stringify(value)} as const;`,
  )
  .join('\n');
const source = await format(
  '// Generated by scripts/client-data.mjs. Do not edit by hand.\n' +
    declarations,
  {
    ...(await resolveConfig('src/data/client-enquiry.ts')),
    filepath: 'src/data/client-enquiry.ts',
  },
);
fs.writeFileSync('src/data/client-enquiry.ts', source);
